export const STRINGS = { en, he };
export const LOCALES = { en: 'en-US', he: 'he-IL' };

export function makeT(lang) {
  const dict = STRINGS[lang] || en;
  const t = (key, vars = {}) => String(dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  t.lang = STRINGS[lang] ? lang : 'en';
  t.locale = LOCALES[t.lang];
  return t;
}

export const LangContext = createContext(makeT('en'));
export const useT = () => useContext(LangContext);
